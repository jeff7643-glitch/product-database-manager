import csv
import io
import os
import secrets
from decimal import Decimal, InvalidOperation
from functools import wraps

import psycopg
from flask import (
    Flask,
    abort,
    flash,
    redirect,
    render_template,
    request,
    session,
    url_for,
)
from werkzeug.security import check_password_hash


PAGE_SIZE = 50
MAX_IMPORT_ROWS = 5_000
PRODUCT_FIELDS = ("sku", "name", "category", "description", "price", "quantity")
CSV_FIELDS = ("sku", "name", "price", "quantity", "category", "description")


def create_app():
    app = Flask(__name__)
    app.config.update(
        SECRET_KEY=os.getenv("SECRET_KEY"),
        DATABASE_URL=os.getenv("DATABASE_URL"),
        ADMIN_USERNAME=os.getenv("ADMIN_USERNAME"),
        ADMIN_PASSWORD_HASH=os.getenv("ADMIN_PASSWORD_HASH"),
        MAX_CONTENT_LENGTH=5 * 1024 * 1024,
        SESSION_COOKIE_HTTPONLY=True,
        SESSION_COOKIE_SAMESITE="Lax",
        SESSION_COOKIE_SECURE=os.getenv("SESSION_COOKIE_SECURE") == "1",
    )

    @app.before_request
    def check_configuration_and_csrf():
        required = ("SECRET_KEY", "DATABASE_URL", "ADMIN_USERNAME", "ADMIN_PASSWORD_HASH")
        missing = [key for key in required if not app.config.get(key)]
        if missing:
            raise RuntimeError(f"Missing required configuration: {', '.join(missing)}")
        if request.method == "POST":
            expected = session.get("_csrf_token", "")
            supplied = request.form.get("_csrf_token", "")
            if not secrets.compare_digest(expected, supplied):
                abort(400, description="The form expired or its security token was invalid. Please try again.")

    @app.context_processor
    def csrf_context():
        def csrf_token():
            if "_csrf_token" not in session:
                session["_csrf_token"] = secrets.token_urlsafe(32)
            return session["_csrf_token"]

        return {"csrf_token": csrf_token}

    @app.errorhandler(psycopg.Error)
    def handle_database_error(error):
        app.logger.exception("Database operation failed", exc_info=error)
        return render_template(
            "error.html",
            message="The database operation failed. Check the database connection and try again.",
        ), 503

    @app.errorhandler(psycopg.errors.UniqueViolation)
    def handle_duplicate_sku(error):
        app.logger.info("A product with a duplicate SKU was rejected")
        return render_template(
            "error.html",
            message="That SKU already exists. No products from this operation were saved.",
        ), 409

    def login_required(view):
        @wraps(view)
        def wrapped(*args, **kwargs):
            if not session.get("authenticated"):
                return redirect(url_for("login", next=request.full_path))
            return view(*args, **kwargs)

        return wrapped

    @app.cli.command("init-db")
    def init_db():
        """Create the products table and its indexes."""
        with connect_db(app.config["DATABASE_URL"]) as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS products (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    sku VARCHAR(64) NOT NULL UNIQUE,
                    name VARCHAR(200) NOT NULL,
                    category VARCHAR(100) NOT NULL DEFAULT '',
                    description TEXT NOT NULL DEFAULT '',
                    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
                    quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """
            )
            connection.execute(
                "CREATE INDEX IF NOT EXISTS products_category_name_idx ON products (category, name)"
            )
        print("Database initialized.")

    @app.route("/login", methods=("GET", "POST"))
    def login():
        if session.get("authenticated"):
            return redirect(url_for("products"))
        if request.method == "POST":
            username = request.form.get("username", "")
            password = request.form.get("password", "")
            valid_username = secrets.compare_digest(username, app.config["ADMIN_USERNAME"])
            valid_password = check_password_hash(app.config["ADMIN_PASSWORD_HASH"], password)
            if valid_username and valid_password:
                session.clear()
                session["authenticated"] = True
                destination = request.args.get("next", "")
                if destination.startswith("/") and not destination.startswith("//"):
                    return redirect(destination)
                return redirect(url_for("products"))
            flash("Invalid username or password.", "error")
        return render_template("login.html")

    @app.post("/logout")
    @login_required
    def logout():
        session.clear()
        return redirect(url_for("login"))

    @app.get("/")
    @login_required
    def products():
        query = request.args.get("q", "").strip()
        category = request.args.get("category", "").strip()
        page = max(request.args.get("page", 1, type=int) or 1, 1)
        conditions = []
        parameters = []
        if query:
            conditions.append("(sku ILIKE %s OR name ILIKE %s OR category ILIKE %s)")
            pattern = f"%{query}%"
            parameters.extend((pattern, pattern, pattern))
        if category:
            conditions.append("category = %s")
            parameters.append(category)
        where_clause = f" WHERE {' AND '.join(conditions)}" if conditions else ""
        offset = (page - 1) * PAGE_SIZE

        with connect_db(app.config["DATABASE_URL"]) as connection:
            total = connection.execute(
                f"SELECT COUNT(*) FROM products{where_clause}", parameters
            ).fetchone()[0]
            rows = connection.execute(
                f"""
                SELECT id, sku, name, category, description, price, quantity
                FROM products{where_clause}
                ORDER BY name, sku
                LIMIT %s OFFSET %s
                """,
                [*parameters, PAGE_SIZE, offset],
            ).fetchall()
            categories = [
                row[0]
                for row in connection.execute(
                    "SELECT DISTINCT category FROM products WHERE category <> '' ORDER BY category"
                ).fetchall()
            ]
        return render_template(
            "products.html",
            products=rows,
            categories=categories,
            query=query,
            selected_category=category,
            page=page,
            page_count=max((total + PAGE_SIZE - 1) // PAGE_SIZE, 1),
            total=total,
        )

    @app.route("/products/new", methods=("GET", "POST"))
    @login_required
    def create_product():
        if request.method == "POST":
            product, errors = validate_product(request.form)
            if errors:
                return render_template("product_form.html", product=product, errors=errors, editing=False), 422
            with connect_db(app.config["DATABASE_URL"]) as connection:
                connection.execute(
                    """
                    INSERT INTO products (sku, name, category, description, price, quantity)
                    VALUES (%(sku)s, %(name)s, %(category)s, %(description)s, %(price)s, %(quantity)s)
                    """,
                    product,
                )
            flash(f"Product {product['sku']} added.", "success")
            return redirect(url_for("products"))
        return render_template("product_form.html", product={}, errors={}, editing=False)

    @app.route("/products/<int:product_id>/edit", methods=("GET", "POST"))
    @login_required
    def edit_product(product_id):
        if request.method == "POST":
            product, errors = validate_product(request.form)
            if errors:
                product["id"] = product_id
                return render_template("product_form.html", product=product, errors=errors, editing=True), 422
            with connect_db(app.config["DATABASE_URL"]) as connection:
                result = connection.execute(
                    """
                    UPDATE products
                    SET sku = %(sku)s, name = %(name)s, category = %(category)s,
                        description = %(description)s, price = %(price)s,
                        quantity = %(quantity)s, updated_at = CURRENT_TIMESTAMP
                    WHERE id = %(id)s
                    """,
                    {**product, "id": product_id},
                )
                if result.rowcount == 0:
                    abort(404)
            flash(f"Product {product['sku']} updated.", "success")
            return redirect(url_for("products"))

        with connect_db(app.config["DATABASE_URL"]) as connection:
            row = connection.execute(
                """
                SELECT id, sku, name, category, description, price, quantity
                FROM products WHERE id = %s
                """,
                (product_id,),
            ).fetchone()
        if row is None:
            abort(404)
        product = dict(zip(("id", *PRODUCT_FIELDS), row))
        return render_template("product_form.html", product=product, errors={}, editing=True)

    @app.post("/products/<int:product_id>/delete")
    @login_required
    def delete_product(product_id):
        with connect_db(app.config["DATABASE_URL"]) as connection:
            result = connection.execute("DELETE FROM products WHERE id = %s", (product_id,))
        if result.rowcount == 0:
            abort(404)
        flash("Product deleted.", "success")
        return redirect(url_for("products"))

    @app.route("/import", methods=("GET", "POST"))
    @login_required
    def import_csv():
        if request.method == "POST":
            uploaded = request.files.get("file")
            if uploaded is None or not uploaded.filename:
                return render_template("import.html", error="Choose a CSV file to import."), 422
            try:
                content = uploaded.stream.read().decode("utf-8-sig")
            except UnicodeDecodeError:
                return render_template("import.html", error="The file must be UTF-8 encoded."), 422
            records, errors = parse_csv(content)
            if errors:
                return render_template("import.html", error=None, errors=errors), 422
            if not records:
                return render_template("import.html", error="The CSV file contains no product rows."), 422
            with connect_db(app.config["DATABASE_URL"]) as connection:
                with connection.transaction():
                    connection.cursor().executemany(
                        """
                        INSERT INTO products (sku, name, category, description, price, quantity)
                        VALUES (%(sku)s, %(name)s, %(category)s, %(description)s, %(price)s, %(quantity)s)
                        """,
                        records,
                    )
            flash(f"Imported {len(records)} products.", "success")
            return redirect(url_for("products"))
        return render_template("import.html", error=None, errors=[])

    return app


def connect_db(database_url):
    return psycopg.connect(database_url)


def validate_product(source):
    product = {}
    errors = {}
    for field in ("sku", "name", "category", "description"):
        value = source.get(field, "").strip()
        product[field] = value
        max_length = {"sku": 64, "name": 200, "category": 100, "description": 2_000}[field]
        if field in ("sku", "name") and not value:
            errors[field] = f"{field.title()} is required."
        elif len(value) > max_length:
            errors[field] = f"{field.title()} must be {max_length} characters or fewer."

    try:
        price = Decimal(source.get("price", "").strip())
        if not price.is_finite() or price < 0:
            raise InvalidOperation
        rounded_price = price.quantize(Decimal("0.01"))
        if rounded_price != price:
            raise InvalidOperation
        price = rounded_price
        if price > Decimal("99999999.99"):
            raise InvalidOperation
        product["price"] = price
    except (InvalidOperation, ValueError):
        product["price"] = source.get("price", "")
        errors["price"] = "Enter a valid non-negative price with up to two decimal places."

    quantity_text = source.get("quantity", "0").strip()
    try:
        quantity = int(quantity_text)
        if quantity < 0 or quantity > 2_147_483_647:
            raise ValueError
        product["quantity"] = quantity
    except ValueError:
        product["quantity"] = quantity_text
        errors["quantity"] = "Enter a non-negative whole-number quantity."
    return product, errors


def parse_csv(content):
    errors = []
    records = []
    reader = csv.DictReader(io.StringIO(content, newline=""))
    headers = [header.strip().lower() for header in (reader.fieldnames or [])]
    if not {"sku", "name", "price"}.issubset(headers):
        return [], ["CSV headers must include sku, name, and price."]
    if len(headers) != len(set(headers)):
        return [], ["CSV headers must not contain duplicates."]
    if any(header not in CSV_FIELDS for header in headers):
        return [], [f"CSV headers may only use: {', '.join(CSV_FIELDS)}."]

    for line_number, row in enumerate(reader, start=2):
        if line_number - 1 > MAX_IMPORT_ROWS:
            errors.append(f"CSV files may contain at most {MAX_IMPORT_ROWS} product rows.")
            break
        if None in row:
            errors.append(f"Row {line_number}: the row has more columns than the CSV header.")
            continue
        normalized_row = {
            key.strip().lower(): value or ""
            for key, value in row.items()
            if key is not None
        }
        product, row_errors = validate_product(normalized_row)
        if row_errors:
            errors.extend(f"Row {line_number}: {message}" for message in row_errors.values())
        else:
            records.append(product)
    if errors:
        return [], errors
    return records, []


app = create_app()


if __name__ == "__main__":
    app.run()
